export const getProductById = (id) => products.find((product) => product.id === Number(id));

// Related products: same category first, then anything else to fill the row.
export const getRelatedProducts = (product, limit = 4) => {
  const others = products.filter((item) => item.id !== product.id);
  const sameCategory = others.filter((item) => item.category === product.category);
  const rest = others.filter((item) => item.category !== product.category);
  return [...sameCategory, ...rest].slice(0, limit);
};

export const isInStock = (product) => product.availability !== 'Out of Stock';
